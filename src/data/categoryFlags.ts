/**
 * Gets the flag CDN URL for a given category name.
 * 
 * @param category The name of the category/country
 * @param width The image width in pixels (e.g. 16, 24, 32, 40, 48, 64, etc.)
 * @returns The flagcdn.com image URL
 */
export function getFlagUrl(category: string, width: number = 32): string {
  if (!category) return `https://flagcdn.com/w${width}/un.png`;
  
  const normalized = category.trim();
  
  // Try exact match first
  if (categoryFlags[normalized]) {
    return `https://flagcdn.com/w${width}/${categoryFlags[normalized]}.png`;
  }
  
  // Try lowercase match
  const lower = normalized.toLowerCase();
  if (categoryFlags[lower]) {
    return `https://flagcdn.com/w${width}/${categoryFlags[lower]}.png`;
  }
  
  // Default fallback (United Nations flag used as a generic globe/international fallback)
  return `https://flagcdn.com/w${width}/un.png`;
}
